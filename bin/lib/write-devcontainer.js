/**
 * Writes `.devcontainer/devcontainer.json`, `.devcontainer/post-create.sh`,
 * and (when GitHub is enabled) `.devcontainer/post-start.sh` for the current project.
 *
 * Always applies credential-isolation settings (blanks out VS Code git
 * forwarding env vars and disables git auth helpers). When GitHub setup is
 * requested, also mounts the scoped PAT token and configures `gh auth`.
 */

import fs from 'fs';
import path from 'path';

// Pinned to v0.37.2 (80a6fe606f73b19e52b0b330d242e62a6c07be42) to prevent supply-chain risk from a mutable branch ref.
// Download first so echo "n" can answer the interactive telemetry prompt; rtk telemetry disable is belt-and-suspenders.
const RTK_INSTALL = [
  'curl -fsSL https://raw.githubusercontent.com/rtk-ai/rtk/80a6fe606f73b19e52b0b330d242e62a6c07be42/install.sh -o /tmp/rtk-install.sh',
  'echo "n" | sh /tmp/rtk-install.sh',
  'rtk telemetry disable',
].join('\n');

const CLI_INSTALL_MAP = {
  claude:   'npm install -g @anthropic-ai/claude-code',
  gemini:   'npm install -g @google/gemini-cli',
  codex:    'npm install -g @openai/codex',
  opencode: 'npm install -g opencode',
};

const RTK_INIT_BY_CLI = {
  claude:    'rtk init -g',
  codex:     'rtk init -g --codex',
  gemini:    'rtk init -g --gemini',
  opencode:  'rtk init -g --opencode',
};

// Guarded so the plugin marketplace registration and install are skipped when the `.claude`
// volume already contains the plugin from a prior build.
const CAVEMAN_INSTALL_CLAUDE =
  '[ -d "$HOME/.claude/plugins/caveman" ] || (claude plugin marketplace add JuliusBrussee/caveman && claude plugin install caveman@caveman)';

// Guarded so a second container build doesn't re-clone into an already-populated directory.
const SUBAGENTS_CLONE =
  '[ -d "$HOME/.claude/agents/awesome-subagents" ] || (mkdir -p "$HOME/.claude/agents" && git clone --depth=1 https://github.com/VoltAgent/awesome-claude-code-subagents "$HOME/.claude/agents/awesome-subagents")';

const ISOLATION_VSCODE_SETTINGS = {
  'git.terminalAuthentication': false,
  'github.gitAuthentication': false,
  'dev.containers.copyGitConfig': false,
  'dev.containers.gitCredentialHelperConfigLocation': 'none',
};

/**
 * Per-template default user and home directory. Keyed by `templateName`
 * (matches `TEMPLATES[].name` in devcontainer-templates.js).
 *
 * Mount targets MUST be absolute paths — Docker rejects unresolved variables
 * like `${containerEnv:HOME}` because `mounts` is consumed by `docker run`
 * before the container exists, so `containerEnv:*` cannot be resolved at
 * that point. We therefore write a literal home path and pin `remoteUser`
 * to the user that the base image actually ships with.
 */
const TEMPLATE_USERS = {
  'Node.js':              { user: 'node',   home: '/home/node' },
  'Python':               { user: 'vscode', home: '/home/vscode' },
  'Python + Node':        { user: 'vscode', home: '/home/vscode' },
  'Minimal Ubuntu':       { user: 'vscode', home: '/home/vscode' },
  'Full Dev Environment': { user: 'vscode', home: '/home/vscode' },
};

const DEFAULT_USER = { user: 'vscode', home: '/home/vscode' };

const ISOLATION_ENV = {
  SSH_AUTH_SOCK: '',
  GIT_ASKPASS: '',
  VSCODE_GIT_ASKPASS_NODE: '',
  VSCODE_GIT_ASKPASS_MAIN: '',
  VSCODE_GIT_IPC_HANDLE: '',
  GITHUB_TOKEN: '',
  GH_TOKEN: '',
  GCM_INTERACTIVE: 'never',
  GIT_TERMINAL_PROMPT: '0',
};

/**
 * Derive a Docker-safe slug from the current project directory name.
 * Used to scope named volumes per project so multiple ralph projects
 * can coexist without overwriting each other's gh / claude state.
 *
 * @returns {string} e.g. "my-project"
 */
function _projectSlug() {
  return path.basename(process.cwd())
    .toLowerCase()
    .replace(/^\.+/, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

/**
 * Build the content of .devcontainer/post-create.sh.
 * Each step is a separate line with a comment explaining why it exists.
 */
function _buildPostCreateScript({ cliInstall, fixOwnership, rtkInstall, rtkInit, caveman, subagents, credCleanup }) {
  const sections = [
    [
      '#!/usr/bin/env bash',
      '# Generated by ralph — re-running scaffold overwrites this file.',
      'set -euo pipefail',
    ],
  ];

  if (cliInstall) {
    sections.push([
      '# Install the AI CLI',
      cliInstall,
    ]);
  }

  if (fixOwnership) {
    sections.push([
      '# Fix ownership of named volumes (Docker creates them as root, container runs as the dev user)',
      fixOwnership,
    ]);
  }

  sections.push([
    '# Install RTK (commit-pinned to prevent supply-chain risk from a mutable branch ref)',
    rtkInstall,
  ]);

  sections.push([
    '# Initialize RTK for this CLI',
    rtkInit,
  ]);

  if (caveman) {
    sections.push([
      '# Install the Caveman plugin (guarded so a rebuilt volume skips re-install)',
      caveman,
    ]);
  }

  if (subagents) {
    sections.push([
      '# Clone awesome-claude-code-subagents (guarded so a rebuilt volume skips re-clone)',
      subagents,
    ]);
  }

  if (credCleanup) {
    sections.push([
      '# Remove the VS Code credential helper injected at container build time',
      credCleanup,
    ]);
  }

  return sections.map(s => s.join('\n')).join('\n\n') + '\n';
}

/** Build the content of .devcontainer/post-start.sh. */
function _buildPostStartScript() {
  return [
    '#!/usr/bin/env bash',
    '# Generated by ralph — re-running scaffold overwrites this file.',
    'set -euo pipefail',
    '',
    'WORKSPACE_FOLDER="${1:?containerWorkspaceFolder argument required}"',
    '',
    '# Clear VS Code git credential forwarders that re-inject on each container start',
    'unset VSCODE_GIT_IPC_HANDLE GIT_ASKPASS VSCODE_GIT_ASKPASS_NODE VSCODE_GIT_ASKPASS_MAIN',
    '',
    '# Remove credential helper added by VS Code',
    'git config --global --unset-all credential.helper || true',
    '',
    '# Authenticate gh CLI with the project-scoped PAT',
    'gh auth login --with-token < "${WORKSPACE_FOLDER}/.ralph/token"',
    'gh auth setup-git',
    '',
  ].join('\n');
}

/**
 * Build and write `.devcontainer/devcontainer.json`, `post-create.sh`,
 * and (when GitHub is enabled) `post-start.sh`.
 *
 * @param {object}  config           - Base devcontainer config from a template.
 * @param {string}  templateName     - Human-readable template name for log output.
 * @param {boolean} setupGitHub      - Whether to mount a PAT token and configure gh CLI.
 * @param {string|null} _tokenPath   - Unused; kept for backward compatibility.
 * @param {string}  cliName          - The AI CLI selected by the user (e.g. 'claude').
 * @param {object}  [tools]          - Optional tool opt-ins.
 * @param {boolean} [tools.caveman]  - Install the Caveman debugging plugin.
 * @param {boolean} [tools.subagents] - Clone the awesome-claude-code-subagents list.
 */
export function writeDevContainer(config, templateName, setupGitHub = false, _tokenPath = null, _debug = false, cliName = 'claude', tools = {}) {
  const devcontainerDir = path.resolve(process.cwd(), '.devcontainer');
  const devcontainerFile = path.join(devcontainerDir, 'devcontainer.json');

  if (!fs.existsSync(devcontainerDir)) {
    fs.mkdirSync(devcontainerDir, { recursive: true });
  }

  const slug = _projectSlug();
  const tokenExists = fs.existsSync(path.join(process.cwd(), '.ralph', 'token'));
  // Mount and configure gh auth whenever a token is present, even if the user
  // skipped the GitHub setup step on a subsequent run.
  const useGitHub = setupGitHub || tokenExists;
  const { user: remoteUser, home } = TEMPLATE_USERS[templateName] ?? DEFAULT_USER;

  const finalConfig = {
    ...config,
    remoteUser,
    customizations: {
      ...config.customizations,
      vscode: {
        ...config.customizations?.vscode,
        settings: {
          ...config.customizations?.vscode?.settings,
          ...ISOLATION_VSCODE_SETTINGS,
        },
      },
    },
    containerEnv: {
      ...config.containerEnv,
      ...ISOLATION_ENV,
    },
  };

  if (cliName === 'claude') {
    // Persist claude configuration (e.g. agent installations) in a project-scoped
    // volume so switching between ralph projects doesn't clobber each other's state.
    finalConfig.mounts = [
      ...(finalConfig.mounts || []),
      { source: `claude-agents-vol-${slug}`, target: `${home}/.claude`, type: 'volume' },
    ];
  }

  if (useGitHub) {
    finalConfig.features = {
      ...finalConfig.features,
      'ghcr.io/devcontainers/features/github-cli:1': {},
    };

    // Use ${localWorkspaceFolder} so the token path is resolved by the devcontainer
    // runtime — works on macOS, Linux, and Windows without any OS-specific logic.
    // The project-scoped volume name prevents cross-project gh auth collisions.
    finalConfig.mounts = [
      ...(finalConfig.mounts || []),
      { source: `gh-config-${slug}`, target: `${home}/.config/gh`, type: 'volume' },
    ];
  }

  // Named volumes are created owned by root, but we run as `remoteUser`.
  // chown the mountpoints we added so subsequent commands (rtk init, claude
  // plugin install, gh auth) can write into them. MS dev container base
  // images grant passwordless sudo to their default user.
  const ownedMountPaths = [];
  if (cliName === 'claude') ownedMountPaths.push(`${home}/.claude`);
  if (useGitHub) ownedMountPaths.push(`${home}/.config/gh`);
  const fixOwnership = ownedMountPaths.length
    ? `sudo chown -R ${remoteUser}:${remoteUser} ${ownedMountPaths.join(' ')}`
    : null;

  const cliInstall = CLI_INSTALL_MAP[cliName] ?? null;

  const postCreateContent = _buildPostCreateScript({
    cliInstall,
    fixOwnership,
    rtkInstall: RTK_INSTALL,
    rtkInit: RTK_INIT_BY_CLI[cliName] ?? RTK_INIT_BY_CLI.claude,
    caveman: (tools.caveman && cliName === 'claude') ? CAVEMAN_INSTALL_CLAUDE : null,
    subagents: (tools.subagents && cliName === 'claude') ? SUBAGENTS_CLONE : null,
    credCleanup: useGitHub ? 'git config --global --unset-all credential.helper || true' : null,
  });

  fs.writeFileSync(path.join(devcontainerDir, 'post-create.sh'), postCreateContent);
  finalConfig.postCreateCommand = 'bash .devcontainer/post-create.sh';

  if (useGitHub) {
    fs.writeFileSync(path.join(devcontainerDir, 'post-start.sh'), _buildPostStartScript());
    finalConfig.postStartCommand = 'bash .devcontainer/post-start.sh ${containerWorkspaceFolder}';
  }

  fs.writeFileSync(devcontainerFile, JSON.stringify(finalConfig, null, 2));

  _printSummary(templateName, useGitHub);
}

/** @param {string} templateName @param {boolean} setupGitHub */
function _printSummary(templateName, setupGitHub) {
  console.log(`\nDev Container configured with "${templateName}" template.`);
  console.log('   Created: .devcontainer/devcontainer.json');
  console.log('   Created: .devcontainer/post-create.sh');
  if (setupGitHub) {
    console.log('   Created: .devcontainer/post-start.sh');
    console.log('   GitHub PAT token will be isolated to this repository only.');
  }
  console.log('   Isolation enabled: Git credentials are NOT forwarded from host.');
  console.log('\nNext steps:');
  console.log('  1. Open this folder in VS Code');
  console.log('  2. Install the "Dev Containers" extension if not already installed');
  console.log('  3. Click "Reopen in Container" when prompted');
  console.log('     (or use Cmd+Shift+P > "Dev Containers: Reopen in Container")');
  console.log('  4. Run ralph inside the container for a safe, isolated environment\n');
}
